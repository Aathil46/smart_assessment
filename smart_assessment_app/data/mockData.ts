function generateConceptResults(concepts: string[], baseScore: number): ConceptResult[] {
  return concepts.map((concept, i) => {
    const variance = ((i * 17 + 23) % 30) - 15;
    const score = Math.max(20, Math.min(100, baseScore + variance));
    const total = 3 + (i % 3);
    const correctCount = Math.round((score / 100) * total);
    return {
      concept,
      score,
      mastery: score >= 80 ? 'strong' : score >= 60 ? 'medium' : 'weak',
      correctCount,
      totalCount: total,
    };
  });
}

